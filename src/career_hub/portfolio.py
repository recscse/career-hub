"""Static portfolio (index.html + data.json + resume.md) built ONLY from items marked public.

Privacy rules, enforced here and covered by tests:
- Only rows with visibility='public' are included.
- Profile `preferences` are never exported. Skill `evidence` is never exported (it can name private repos).
- Repo facts (languages, stars) are joined to a project only when that repo is public too.
- Output is plain HTML with every value escaped, no scripts and no external requests.
"""

from __future__ import annotations

import html
import json
import re
import sqlite3
from datetime import datetime, timezone
from pathlib import Path
from urllib.parse import urlparse

from . import db, resume

GENERATOR = "career-context-hub"
HTML_MARKER = "<!-- generated by career-context-hub -->"
PROFILE_PUBLIC_FIELDS = ("name", "headline", "summary", "location", "links")
OUTPUT_FILES = ("index.html", "data.json", "resume.md")


class PortfolioError(ValueError):
    pass


def safe_url(url: str | None) -> str | None:
    """Return the URL only if it is http(s) with a host (blocks javascript:, data:, etc.)."""
    if not url:
        return None
    url = url.strip()
    p = urlparse(url)
    return url if p.scheme in ("http", "https") and p.netloc else None


def build_site_data(con: sqlite3.Connection, user_id: int, generated_at: str | None = None) -> dict:
    profile = db.get_profile(con, user_id)
    pub = "public"
    repos = {r["project_id"]: r for r in db.list_items(con, user_id, "repos", pub) if r["project_id"]}
    projects = []
    for p in db.list_items(con, user_id, "projects", pub):
        item = {k: p[k] for k in ("name", "description", "stack", "url", "outcome")}
        r = repos.get(p["id"])
        if r:
            item["languages_pct_by_bytes"] = json.loads(r["languages"] or "{}")
            item["stars"] = r["stars"]
            item["homepage"] = r["homepage"]
            item["my_commits_lower_bound"] = r["my_commits"]
        projects.append(item)
    return {
        "generator": GENERATOR,
        "generated_at": generated_at or datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "profile": {k: profile.get(k) for k in PROFILE_PUBLIC_FIELDS if profile.get(k)},
        "skills": [
            {k: s[k] for k in ("name", "level", "years")} for s in db.list_items(con, user_id, "skills", pub)
        ],
        "experience": [
            {k: e[k] for k in ("role", "company", "start_date", "end_date", "summary", "achievements")}
            for e in sorted(db.list_items(con, user_id, "experience", pub), key=lambda e: e["start_date"] or "", reverse=True)
        ],
        "projects": projects,
        "open_source": [
            {k: c[k] for k in ("repo", "title", "url")}
            for c in db.list_items(con, user_id, "contributions", pub)
            if (c["status"] or "").lower() == "merged"
        ],
    }


# ---- HTML -------------------------------------------------------------------------

CSS = """
:root{--bg:#fff;--fg:#1b1f24;--muted:#57606a;--line:#d8dee4;--accent:#0b5fff;--chip:#eef2f7}
@media (prefers-color-scheme:dark){:root{--bg:#0f1318;--fg:#e6e9ee;--muted:#9aa4b2;--line:#2a313b;--accent:#6ea0ff;--chip:#1b222b}}
*{box-sizing:border-box}body{margin:0;background:var(--bg);color:var(--fg);font:16px/1.6 system-ui,-apple-system,Segoe UI,Roboto,sans-serif}
main{max-width:46rem;margin:0 auto;padding:2.5rem 1rem 4rem}h1{margin:0;font-size:2rem}h2{margin:2.5rem 0 .75rem;font-size:1.15rem;border-bottom:1px solid var(--line);padding-bottom:.3rem}
h3{margin:0;font-size:1rem}.muted{color:var(--muted)}a{color:var(--accent)}ul{padding-left:1.2rem}
.chips{display:flex;flex-wrap:wrap;gap:.4rem;list-style:none;padding:0}.chips li{background:var(--chip);border-radius:999px;padding:.1rem .7rem;font-size:.9rem}
.item{margin:1rem 0}.langs{font-size:.85rem;color:var(--muted)}
"""


def _e(value) -> str:
    return html.escape("" if value is None else str(value), quote=True)


def _link(url: str | None, label: str | None = None) -> str:
    safe = safe_url(url)
    if not safe:
        return _e(label or "")
    return f'<a href="{_e(safe)}" rel="noopener noreferrer">{_e(label or safe)}</a>'


def _links_text(text: str) -> str:
    parts = []
    for token in re.split(r"[,\s]+", text.strip()):
        if token:
            parts.append(_link(token) if safe_url(token) else _e(token))
    return " &middot; ".join(parts)


def render_html(data: dict) -> str:
    p = data["profile"]
    name = p.get("name") or "Portfolio"
    out = [
        "<!doctype html>", HTML_MARKER, '<html lang="en"><head><meta charset="utf-8">',
        '<meta name="viewport" content="width=device-width,initial-scale=1">',
        f"<title>{_e(name)}</title>",
        f'<meta name="description" content="{_e(p.get("headline") or name)}">',
        f"<style>{CSS}</style></head><body><main>",
        f"<header><h1>{_e(name)}</h1>",
    ]
    if p.get("headline"):
        out.append(f'<p class="muted">{_e(p["headline"])}</p>')
    meta = []
    if p.get("location"):
        meta.append(_e(p["location"]))
    if p.get("links"):
        meta.append(_links_text(p["links"]))
    if meta:
        out.append(f'<p class="muted">{" &middot; ".join(meta)}</p>')
    out.append("</header>")
    if p.get("summary"):
        out.append(f'<section><h2>About</h2><p>{_e(p["summary"])}</p></section>')
    if data["skills"]:
        chips = "".join(f"<li>{_e(s['name'])}</li>" for s in data["skills"])
        out.append(f'<section><h2>Skills</h2><ul class="chips">{chips}</ul></section>')
    if data["experience"]:
        out.append("<section><h2>Experience</h2>")
        for e in data["experience"]:
            head = _e(e["role"]) + (f", {_e(e['company'])}" if e["company"] else "")
            out.append(f'<div class="item"><h3>{head}</h3><div class="muted">{_e(e["start_date"] or "")} &ndash; {_e(e["end_date"] or "Present")}</div>')
            if e["summary"]:
                out.append(f"<p>{_e(e['summary'])}</p>")
            lines = [ln.strip().lstrip("-* ") for ln in (e["achievements"] or "").splitlines() if ln.strip()]
            if lines:
                out.append("<ul>" + "".join(f"<li>{_e(ln)}</li>" for ln in lines) + "</ul>")
            out.append("</div>")
        out.append("</section>")
    if data["projects"]:
        out.append("<section><h2>Projects</h2>")
        for pr in data["projects"]:
            out.append(f'<div class="item"><h3>{_link(pr["url"], pr["name"]) if safe_url(pr["url"]) else _e(pr["name"])}</h3>')
            if pr["description"]:
                out.append(f"<p>{_e(pr['description'])}</p>")
            langs = pr.get("languages_pct_by_bytes") or {}
            if langs:
                text = ", ".join(f"{_e(k)} {v:g}%" for k, v in list(langs.items())[:4])
                out.append(f'<div class="langs">Languages (share of code): {text}</div>')
            elif pr["stack"]:
                out.append(f'<div class="langs">{_e(pr["stack"])}</div>')
            if pr["outcome"]:
                out.append(f'<div class="muted">{_e(pr["outcome"])}</div>')
            if safe_url(pr.get("homepage")):
                out.append(f"<div>{_link(pr['homepage'], 'Live site')}</div>")
            out.append("</div>")
        out.append("</section>")
    if data["open_source"]:
        out.append("<section><h2>Open-source contributions</h2><ul>")
        for c in data["open_source"]:
            out.append(f"<li>{_e(c['repo'])}: {_link(c['url'], c['title'] or 'pull request')}</li>")
        out.append("</ul></section>")
    out.append(f'<p class="muted" style="margin-top:3rem;font-size:.85rem">Generated {_e(data["generated_at"][:10])}</p>')
    out.append("</main></body></html>")
    return "\n".join(out) + "\n"


# ---- writing files ----------------------------------------------------------------


def _ours(path: Path) -> bool:
    try:
        text = path.read_text(encoding="utf-8", errors="ignore")
    except OSError:
        return False
    if path.suffix == ".json":
        try:
            return json.loads(text).get("generator") == GENERATOR
        except ValueError:
            return False
    if path.suffix == ".html":
        return HTML_MARKER in text
    return text.startswith("<!-- generated by career-context-hub -->")


def build(con: sqlite3.Connection, user_id: int, out_dir: str | Path, overwrite: bool = False) -> dict:
    """Write index.html, data.json and resume.md. Refuses to replace files this tool did not create."""
    out = Path(out_dir).expanduser().resolve()
    blocked = [n for n in OUTPUT_FILES if (out / n).exists() and not overwrite and not _ours(out / n)]
    if blocked:
        raise PortfolioError(
            f"{out} already contains {blocked} that this tool did not generate; choose another folder "
            "or pass overwrite=True"
        )
    data = build_site_data(con, user_id)
    md = HTML_MARKER + "\n" + resume.export_markdown(con, user_id, public_only=True)
    out.mkdir(parents=True, exist_ok=True)
    files = {
        "data.json": json.dumps(data, indent=2, ensure_ascii=False) + "\n",
        "index.html": render_html(data),
        "resume.md": md,
    }
    for name, text in files.items():
        (out / name).write_text(text, encoding="utf-8", newline="\n")
    counts = {k: len(v) for k, v in data.items() if isinstance(v, list)}
    return {"folder": str(out), "files": list(files), "included": counts}
